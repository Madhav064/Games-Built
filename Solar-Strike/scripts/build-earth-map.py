"""Builds src/engine/earthMap.ts: Earth's real coastlines and colours, packed small.

Sources (both public domain, from Natural Earth, https://www.naturalearthdata.com):
  - Coastlines: ne_50m_land.geojson
    (https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_land.geojson)
  - Colours:    NE1_50M_SR_W.tif, "Natural Earth I with Shaded Relief and Water"
    (https://naciscdn.org/naturalearth/50m/raster/NE1_50M_SR_W.zip)

Usage:  python scripts/build-earth-map.py <ne_50m_land.geojson> <NE1_50M_SR_W.tif>

Output layout matches the planet surface lookup (planetData.ts): LUT_W x LUT_H cells,
row 0 = south pole, and the lookup's longitude runs the opposite way to geographic
longitude, so both axes of the map images are flipped.
"""
import base64
import json
import sys

from PIL import Image, ImageDraw, ImageEnhance

LUT_W, LUT_H = 512, 256
PALETTE = 128  # colours after quantising
SUPER = 8      # land mask is drawn at 8x and averaged down

Image.MAX_IMAGE_PIXELS = None


def land_mask(geojson_path):
    W, H = LUT_W * SUPER, LUT_H * SUPER
    img = Image.new('L', (W, H), 0)
    draw = ImageDraw.Draw(img)

    def px(pt):
        lon, lat = pt[0], pt[1]
        return ((lon + 180) / 360 * W, (90 - lat) / 180 * H)

    with open(geojson_path, encoding='utf-8') as f:
        data = json.load(f)
    for feat in data['features']:
        g = feat['geometry']
        polys = [g['coordinates']] if g['type'] == 'Polygon' else g['coordinates']
        for poly in polys:
            draw.polygon([px(p) for p in poly[0]], fill=255)
            for hole in poly[1:]:
                draw.polygon([px(p) for p in hole], fill=0)
    return img.resize((LUT_W, LUT_H), Image.BOX)


def grade(colour, mask):
    """Atlas colours -> 'seen from space': richer land, deep blue seas (shallows stay lighter)."""
    land = ImageEnhance.Color(colour).enhance(1.75)
    land = ImageEnhance.Contrast(land).enhance(1.15)
    land = ImageEnhance.Brightness(land).enhance(0.8)
    # Ocean: the raster's water is lighter over shallow shelves; keep that as a depth cue.
    lum = colour.convert('L')
    lo, hi = lum.getextrema()
    deep, shallow = (8, 30, 82), (30, 96, 160)
    ocean = Image.new('RGB', colour.size)
    op, lp = ocean.load(), lum.load()
    for y in range(colour.size[1]):
        for x in range(colour.size[0]):
            t = ((lp[x, y] - lo) / max(1, hi - lo)) ** 2.2
            op[x, y] = tuple(int(deep[k] + (shallow[k] - deep[k]) * t) for k in range(3))
    return Image.composite(land, ocean, mask)


def main():
    geo, tif = sys.argv[1], sys.argv[2]
    mask = land_mask(geo).rotate(180)
    colour = Image.open(tif).convert('RGB').resize((LUT_W, LUT_H), Image.LANCZOS).rotate(180)
    colour = grade(colour, mask)
    colour.rotate(180).save('earth-preview.png') if '--preview' in sys.argv else None
    q = colour.quantize(colors=PALETTE, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = bytes(q.getpalette()[:PALETTE * 3])
    idx = q.tobytes()

    bits = bytearray(LUT_W * LUT_H // 8)
    m = mask.tobytes()
    for i, v in enumerate(m):
        if v >= 128:
            bits[i >> 3] |= 1 << (i & 7)

    blob = pal + bytes(bits) + idx
    b64 = base64.b64encode(blob).decode('ascii')
    lines = [b64[i:i + 120] for i in range(0, len(b64), 120)]
    out = [
        '// GENERATED by scripts/build-earth-map.py. Do not edit by hand.',
        '// Earth\'s real coastlines and colours from Natural Earth (public domain).',
        f'// Layout: {PALETTE * 3} bytes palette, then {len(bits)} bytes land bits, then {LUT_W * LUT_H} colour indices.',
        f'export const EARTH_PALETTE_SIZE = {PALETTE};',
        'export const EARTH_MAP_B64 =',
        '  ' + '\n  + '.join(f"'{l}'" for l in lines) + ';',
        '',
    ]
    with open('src/engine/earthMap.ts', 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print('palette', PALETTE, 'bytes', len(blob), 'b64', len(b64), 'land %', round(100 * sum(1 for v in m if v >= 128) / len(m), 1))


if __name__ == '__main__':
    main()
